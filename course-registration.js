// 公式の時間割がない専攻語でも自分で曜日を調べずに遊べるようにする。
// あくまで「ゲーム内の仮配置」で、現実のシラバスの曜日・時限ではない。
function tufsAutoArrangeSelectedCourses(courses) {
  const days = ["月", "火", "水", "木", "金", "土"];
  const periodOrder = [2, 3, 4, 1, 5, 6];
  const slots = [];
  for (const period of periodOrder) {
    for (const day of days) slots.push({day, period});
  }
  // 公式確認済み・本人入力の時限は移動させずに優先する。
  const fixed = new Set(courses.filter(c =>
    courseSlot(c) && !c.scheduleAutoGenerated).map(courseSlot));
  const used = new Set(fixed);
  return courses.map(course => {
    if (courseSlot(course) && !course.scheduleAutoGenerated) return course;
    const slot = slots.find(s => !used.has(`${s.day}-${s.period}`));
    if (!slot) return {...course, day: null, period: null,
      scheduleAutoGenerated: false};
    used.add(`${slot.day}-${slot.period}`);
    return {...course, day: slot.day, period: slot.period,
      scheduleAutoGenerated: true, scheduleVerified: false};
  });
}


function courseTerm(game) { return game.turn <= 3 ? "春" : "秋"; }
// 2年次再履修では、旧学期の成績・履修データを上書きしない。
function courseTermKey(game) {
  const suffix = game.year === 2 && (game.repeatYears?.[2] || 0) > 0
    ? `-R${game.repeatYears[2]}` : "";
  return `${game.year}${suffix}-${courseTerm(game)}学期`;
}
function courseSlot(course) {
  return TUFS_COURSE_DAYS.includes(course.day) &&
    Number(course.period) >= 1 && Number(course.period) <= 6
      ? `${course.day}-${course.period}` : null;
}
function courseCatalog(game) {
  let external = [];
  // 別画面で作った course-planner.html のデータが同じオリジンにあれば再利用する。
  try {
    const saved = JSON.parse(localStorage.getItem("tufs-course-planner-v1") || "null");
    if (saved && Array.isArray(saved.added)) external = saved.added;
  } catch (error) { console.warn("履修登録の旧データは読み込めませんでした", error); }
  // 未修得科目だけを再履修候補へ。過去に合格した科目は除く。
  const passedIds = new Set((game.semesterRecords || []).flatMap(r =>
    (r.courseGrades || []).filter(g => g.passed).map(g => g.id)));
  const repeatCandidates = (game.semesterRecords || []).flatMap(r => {
    const registered = game.courseRegistrations?.[r.key]?.courses || [];
    return registered.filter(c => c.term === courseTerm(game) &&
      (r.courseGrades || []).some(g => g.id === c.id && !g.passed) &&
      !passedIds.has(c.id));
  });
  const joined = [
    ...repeatCandidates,
    ...(game.year === 1 ? TUFS_COURSE_SAMPLES : []),
    ...(typeof tufsSuggestedMajorCourses === "function"
      ? tufsSuggestedMajorCourses(game,courseTerm(game)) : []),
    ...(game.year === 1 && typeof tufsStudentLanguage === "function" &&
        tufsStudentLanguage(game) === "アラビア語"
      ? TUFS_2026_ARABIC_1ST_YEAR : []),
    ...(typeof TUFS_VERIFIED_ENGLISH_2026 !== "undefined" ? TUFS_VERIFIED_ENGLISH_2026 : []),
    ...external,
    ...(Array.isArray(game.customCourses) ? game.customCourses : [])
  ];
  const seen = new Set();
  return joined.filter(course => {
    if (!course || typeof course.id !== "string" || typeof course.name !== "string" ||
        (course.term !== "春" && course.term !== "秋") || seen.has(course.id)) return false;
    if (Number.isInteger(course.minYear) && game.year < course.minYear) return false;
    // 学部別の専修科目は、本人の学部を原則として表示する。
    if (course.faculty && course.faculty !== game.faculty) return false;
    if (typeof tufsCourseEligibility === "function" && !tufsCourseEligibility(game,course).ok) return false;
    seen.add(course.id);
    return true;
  }).map(course => {
    const override = game.courseTimeOverrides?.[course.id];
    const useOverride = !courseSlot(course) &&
      TUFS_COURSE_DAYS.includes(override?.day) &&
      Number.isInteger(override?.period) &&
      override.period >= 1 && override.period <= 6;
    return {
      ...course,
      ...(useOverride ? {
        day: override.day, period: override.period,
        scheduleUserEntered: true
      } : {}),
      credits: courseCreditsByCategory(course.category)
    };
  });
}
function shouldRenderCourseRegistration(game) {
  if (!game || game.year < 1 || game.year > 6 ||
      (game.turn !== 1 && game.turn !== 4) ||
      game.pendingResult || game.gradeNotice ||
      game.lifeEventResult || game.lifeEventStage ||
      ["yearOneComplete", "yearTwoComplete", "yearThreeComplete",
        "yearFourComplete", "yearFiveComplete", "yearSixComplete"].some(flag => game[flag]) ||
      (typeof isStudyLeaveYear === "function" && isStudyLeaveYear(game))) return false;
  const key = courseTermKey(game);
  return !game.courseRegistrations?.[key] &&
    !(game.semesterRecords || []).some(record => record.key === key);
}
function courseElement(tag, label, className) {
  const el = document.createElement(tag);
  if (label !== undefined) el.textContent = String(label);
  if (className) el.className = className;
  return el;
}
function courseButton(label, handler, className = "") {
  const b = courseElement("button", label, className);
  b.type = "button";
  b.addEventListener("click", handler);
  return b;
}
function courseGetDraft(game) {
  const key = courseTermKey(game);
  const draft = game.courseDrafts?.[key];
  return Array.isArray(draft) ? draft : [];
}
function courseSaveDraft(ids) {
  const game = loadGame();
  if (!game) return;
  game.courseDrafts ||= {};
  game.courseDrafts[courseTermKey(game)] = ids;
  saveGame(game);
}
function courseHasPassed(game, course) {
  return (game.semesterRecords || []).some(record =>
    (record.courseGrades || []).some(g => g.id === course.id && g.passed));
}
